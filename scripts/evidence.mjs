const shellQuote = (s) => (/'/.test(s) ? `"${s.replace(/(["\\$`])/g, "\\$1")}"` : `'${s}'`);
/** vitest's -t is a regular expression; these are the characters that would change its meaning. */
const forVitest = (name) => name.replace(/[()[\]{}+*?^$\\]/g, "\\$&");

export function runCommand(t) {
  if (t.pkg === "contract") return `(cd contracts/wgp && cargo test --locked ${t.name})`;
  const pkg = PACKAGES[t.pkg];
  return `pnpm --filter ${pkg.filter} exec vitest run ${path.posix.relative(pkg.dir, t.file)} -t ${shellQuote(forVitest(t.name))}`;
}

function curlFor(check, meta) {
  const rpcCall = (url, method, params) => `curl -s ${url} -H 'content-type: application/json' -d '${JSON.stringify({ jsonrpc: "2.0", id: 1, method, params })}'`;
  const view = (method, args) => `${rpcCall(meta.rpc[0], "query", { request_type: "call_function", finality: "final", account_id: check.contract ?? meta.contract, method_name: method, args_base64: b64(args) })} \\\n  | jq -r '.result.result | implode' | jq .`;
  if (check.kind === "view") return view(check.method, check.args ?? {});
  if (check.kind === "holdings") return `${view("get_player", { account_id: check.account })}\n${view("market_account", { account_id: check.account })}`;
  if (check.kind === "senders") {
    return check.of
      .map((id) => `${rpcCall(meta.archivalRpc[0], "tx", { tx_hash: meta.checks[id].hash, sender_account_id: meta.checks[id].sender, wait_until: "FINAL" })} \\\n  | jq -r '.result.transaction | (.actions[0].Delegate.delegate_action.sender_id // .signer_id)'`)
      .join("\n");
  }
  if (check.kind === "account") {
    const account = `${rpcCall(meta.rpc[0], "query", { request_type: "view_account", finality: "final", account_id: check.account })} | jq '.result // .error.cause'`;
    if (!check.keys) return account;
    return `${account}\n${rpcCall(meta.rpc[0], "query", { request_type: "view_access_key_list", finality: "final", account_id: check.account })} | jq '.result.keys'`;
  }
  if (check.kind === "tx") {
    return `${rpcCall(meta.archivalRpc[0], "tx", { tx_hash: check.hash, sender_account_id: check.sender, wait_until: "FINAL" })} \\\n  | jq '{signer: .result.transaction.signer_id, status: .result.status, actions: .result.transaction.actions, logs: [.result.receipts_outcome[].outcome.logs[]]}'`;
  }
  if (check.kind === "http" && check.body) return `curl -s -X POST -H 'content-type: application/json' -d '${JSON.stringify(check.body)}' '${check.url}' | jq .`;
  if (check.kind === "http") return check.text ? `curl -s -o /dev/null -w '%{http_code}\\n' '${check.url}'` : `curl -s '${check.url}' | jq .`;
  if (check.kind === "command") return check.command.join(" ");
  if (check.kind === "git") {
    const lines = [];
    if (check.order) lines.push(`git log --no-walk --date=iso --format='%h %ad %s' ${check.order.map((c) => c.slice(0, 7)).join(" ")}`, ...check.order.slice(1).map((c, i) => `git merge-base --is-ancestor ${check.order[i].slice(0, 7)} ${c.slice(0, 7)} && echo "${check.order[i].slice(0, 7)} came before ${c.slice(0, 7)}"`));
    if (check.ref) lines.push(`git fetch origin ${check.ref}:${check.ref}   # once, if the branch isn't in your clone`, ...(check.commits ?? []).map((c) => `git merge-base --is-ancestor ${c.slice(0, 7)} ${check.ref} && echo "${c.slice(0, 7)} is on ${check.ref}"`), `git merge-base --is-ancestor ${check.ref} HEAD || echo "${check.ref} is not merged into this branch"`);
    if (check.history) lines.push("git log --max-parents=0 --format=%ad --date=short", "git log --format='%h %(trailers:key=co-authored-by,valueonly,separator=%x2C)' | awk 'NF > 1'", "git log -i -E --grep='generated with \\[?claude' --grep='noreply@anthropic\\.com' --format='%h %s'");
    return lines.join("\n");
  }
  if (check.kind === "season") {
    return `${rpcCall(meta.rpc[0], "query", { request_type: "call_function", finality: "final", account_id: check.contract ?? meta.contract, method_name: "get_season", args_base64: b64({ season_id: check.season }) })} \\\n  | jq -r '.result.result | implode' | jq .\ncurl -s -o /dev/null -w '%{http_code}\\n' '${meta.site}/api/seasons/${check.season}/results'`;
  }
  return "";
}

const describeExpect = (e) => {
  const where = e.path ? `\`${e.path}\`` : "the answer";
  // A number read from a document is named by where it is read, so this file doesn't copy it.
  const v = e.doc !== undefined ? `the number ${e.source ?? README} gives (read with \`/${e.doc}/\`)` : `\`${JSON.stringify(e.value)}\``;
  return { eq: `${where} is ${v}`, ne: `${where} is not ${v}`, gte: `${where} is at least ${v}`, lte: `${where} is at most ${v}`, includes: `${where} includes ${v}`, excludes: `${where} does not include ${v}`, anyMatch: `something in ${where} matches \`/${e.value}/\``, type: `${where} is a ${e.value}` }[e.op];
};

const cell = (s) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

/** How much of the claims file is covered by what, counted from the file itself. */
export function coverage(data) {
  const claims = data.claims;
  const isLocal = (id) => data.checks[id].kind === "git";
  const pointers = claims.flatMap((c) => c.code ?? []);
  const needsChain = claims.filter((c) => CHAIN_STATUSES.includes(c.status) && (c.chain ?? []).some((id) => !isLocal(id)));
  const sources = [...new Set(claims.map((c) => c.source))];
  return {
    claims: claims.length,
    sources: sources.length,
    docs: sources.filter((s) => s !== README).length,
    byStatus: Object.fromEntries(STATUSES.map((s) => [s, claims.filter((c) => c.status === s).length])),
    withTests: claims.filter((c) => (c.tests ?? []).length).length,
    testStatusClaims: claims.filter((c) => TEST_STATUSES.includes(c.status)).length,
    testStatusWithTests: claims.filter((c) => TEST_STATUSES.includes(c.status) && (c.tests ?? []).length).length,
    withChain: claims.filter((c) => (c.chain ?? []).length).length,
    withoutTestOrCheck: claims.filter((c) => !(c.tests ?? []).length && !(c.chain ?? []).length).length,
    tests: new Set(claims.flatMap((c) => (c.tests ?? []).map((t) => `${t.file}::${t.name}`))).size,
    checks: Object.keys(data.checks ?? {}).length,
    pointers: pointers.length,
    anchored: pointers.filter((p) => p.anchor).length,
    /** Rows `pnpm evidence` prints as SKIP without --chain: their proof is a chain or site check. */
    offlineSkip: needsChain.length,
    offlinePass: claims.length - needsChain.length,
    contractRows: claims.filter((c) => (c.tests ?? []).some((t) => t.pkg === "contract") || (c.counts ?? []).some((n) => n.pkg === "contract")).length,
  };
}

/** The last line of the table: what the README quotes, structurally. */
export const summaryLine = (n, tally, suffix = "") => `${n} claims: ${tally.PASS} PASS, ${tally.FAIL} FAIL, ${tally.SKIP} SKIP${suffix}.`;
/** The line printed when a rate limit turned rows into SKIP. */
export const rateLimitLine = (n) => `${n} row${n === 1 ? "" : "s"} skipped: rate limited, re-run.`;

/** The README's coverage block, between its two markers. Generated: every number comes from `coverage`. */
export function renderCoverage(data) {
  const c = coverage(data);
  const out = [COVERAGE_START];
  out.push("| | |");
  out.push("|---|---|");
  out.push(`| Claims with a row | ${c.claims}, quoted from this README and ${c.docs} files under \`docs/\` |`);
  out.push(`| By status | ${STATUSES.filter((s) => c.byStatus[s]).map((s) => `${c.byStatus[s]} \`${s}\``).join(" · ")} |`);
  out.push(`| Rows that cite a test | ${c.withTests} of ${c.claims} (${c.tests} different tests). All ${c.testStatusWithTests} rows with the status ${TEST_STATUSES.map((s) => `\`${s}\``).join(", ")} have one; a guard test fails otherwise. |`);
  out.push(`| Rows with a read-only chain or site check | ${c.withChain} of ${c.claims} (${c.checks} different checks) |`);
  out.push(`| Rows with neither (a code pointer only) | ${c.withoutTestOrCheck} |`);
  out.push(`| Code pointers | ${c.pointers}, ${c.anchored === c.pointers ? "each" : `${c.anchored} of them`} anchored to a piece of text that appears once in its file |`);
  out.push(`| \`pnpm evidence\` prints | \`${summaryLine(c.claims, { PASS: c.offlinePass, FAIL: 0, SKIP: c.offlineSkip })}\` The ${c.offlineSkip} SKIP rows are the ${CHAIN_STATUSES.map((s) => `\`${s}\``).join(" and ")} rows, whose proof needs \`--chain\`. In a clone without the branch \`review/contract-v3\`, the rows that check it are SKIP as well. Without Rust installed, the ${c.contractRows} rows that cite a contract test are SKIP too. |`);
  out.push(`| \`pnpm evidence --chain\` prints | \`${summaryLine(c.claims, { PASS: c.claims, FAIL: 0, SKIP: 0 })}\` when every endpoint answers. A rate-limited endpoint is retried, then its rows are SKIP (never FAIL), with the line \`${rateLimitLine(3).replace(/^3 rows/, "N rows")}\` |`);
  out.push(COVERAGE_END);
  return out.join("\n");
}

/** The README with its coverage block replaced by the current one, or null when the markers are missing. */
export function withCoverage(readme, data) {
  const a = readme.indexOf(COVERAGE_START);
  const b = readme.indexOf(COVERAGE_END);
  if (a < 0 || b < a) return null;
  return readme.slice(0, a) + renderCoverage(data) + readme.slice(b + COVERAGE_END.length);
}

