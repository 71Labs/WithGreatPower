class Offline extends Error {
  constructor(message, rateLimited = false) {
    super(message);
    this.rateLimited = rateLimited;
  }
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

/** A request that ran out of time, including one whose answer stopped arriving mid-body. */
export function isTimeout(e) {
  return e?.name === "TimeoutError" || e?.name === "AbortError" || /aborted due to timeout/i.test(e?.message ?? "");
}

/**
 * One request to a public endpoint. A timeout, a rate limit (HTTP 429) or a server error is
 * retried with a growing wait; what still fails after that is an Offline error, which turns
 * the check into a SKIP (never a FAIL) and says whether it was a rate limit.
 * `opts.fetch`, `opts.waits` and `opts.sleep` are for the tests.
 */
export async function fetchJson(url, init = {}, opts = {}) {
  const doFetch = opts.fetch ?? fetch;
  const waits = opts.waits ?? RETRY_WAITS_S;
  const pause = opts.sleep ?? sleep;
  const host = new URL(url).host;
  let last;
  for (let attempt = 0; attempt <= waits.length; attempt++) {
    if (attempt > 0) await pause(waits[attempt - 1] * 1000);
    try {
      const res = await doFetch(url, { ...init, signal: AbortSignal.timeout(CHAIN_TIMEOUT_MS) });
      if (res.status !== 429 && res.status < 500) return res;
      last = new Offline(res.status === 429 ? `${host} rate limited the request (HTTP 429) ${waits.length + 1} times` : `${host} answered HTTP ${res.status}`, res.status === 429);
    } catch (e) {
      last = new Offline(`${host} can't be reached (${e.name === "TimeoutError" ? "timed out" : e.cause?.code ?? e.message})`);
    }
  }
  throw last;
}

async function rpc(urls, method, params) {
  let last;
  for (const url of urls) {
    try {
      const res = await fetchJson(url, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ jsonrpc: "2.0", id: 1, method, params }) });
      return await res.json();
    } catch (e) {
      // The answer can stop arriving after its headers: that is the endpoint being slow, not a wrong answer.
      const err = isTimeout(e) ? new Offline(`${new URL(url).host} timed out while sending its answer`) : e;
      if (!(err instanceof Offline)) throw err;
      last = err;
    }
  }
  throw last;
}

/** `a.b.0`, `a.*.b` (maps over an array) and a trailing `.length`. */
export function pick(value, pathStr) {
  if (!pathStr) return value;
  let cur = [value];
  let mapped = false;
  for (const part of pathStr.split(".")) {
    if (part === "*") {
      cur = cur.flatMap((v) => (Array.isArray(v) ? v : []));
      mapped = true;
    } else cur = cur.map((v) => (v == null ? undefined : part === "length" && (Array.isArray(v) || typeof v === "string") ? v.length : v[part]));
  }
  return mapped ? cur : cur[0];
}

/**
 * An expectation whose number is read from a document instead of being copied here:
 * `{ "path": "runs.verified", "op": "gte", "doc": "finished and verified \\| \\d+ / (\\d+)" }`
 * takes the first capture of that pattern in the README (or `e.source`) as its value. The
 * document is then the only place the number is written.
 */
export function resolveExpect(e, readDoc = read) {
  if (e.doc === undefined) return e;
  const source = e.source ?? README;
  const m = new RegExp(e.doc).exec(readDoc(source));
  if (!m || m[1] === undefined) return { ...e, unresolved: `${source} no longer has the number this check reads (pattern /${e.doc}/)` };
  const n = Number(m[1].replace(/,/g, ""));
  if (!Number.isFinite(n)) return { ...e, unresolved: `${source}: ${JSON.stringify(m[1])} isn't a number (pattern /${e.doc}/)` };
  return { ...e, value: n };
}

/** One expectation against a value. Returns null when it holds, else what was wrong. */
export function expectProblem(value, e) {
  if (e.unresolved) return e.unresolved;
  const got = pick(value, e.path);
  const show = (v) => {
    const s = JSON.stringify(v);
    return s === undefined ? "undefined" : s.length > 160 ? `${s.slice(0, 160)}…` : s;
  };
  const where = e.path || "the answer";
  const num = (v) => (typeof v === "string" && /^-?\d+(\.\d+)?$/.test(v) ? Number(v) : v);
  switch (e.op) {
    case "eq":
      return JSON.stringify(got) === JSON.stringify(e.value) ? null : `${where} is ${show(got)}, expected ${show(e.value)}`;
    case "ne":
      return JSON.stringify(got) !== JSON.stringify(e.value) ? null : `${where} is still ${show(got)}`;
    case "gte":
      return typeof num(got) === "number" && num(got) >= e.value ? null : `${where} is ${show(got)}, expected at least ${e.value}`;
    case "lte":
      return typeof num(got) === "number" && num(got) <= e.value ? null : `${where} is ${show(got)}, expected at most ${e.value}`;
    case "includes":
      return (Array.isArray(got) || typeof got === "string") && got.includes(e.value) ? null : `${where} doesn't include ${show(e.value)}: ${show(got)}`;
    case "excludes":
      return (Array.isArray(got) || typeof got === "string") && !got.includes(e.value) ? null : `${where} ${Array.isArray(got) || typeof got === "string" ? `includes ${show(e.value)}` : `is ${show(got)}, expected a list`}`;
    case "anyMatch": {
      const re = new RegExp(e.value);
      const list = Array.isArray(got) ? got : [got];
      return list.some((v) => typeof v === "string" && re.test(v)) ? null : `nothing in ${where} matches /${e.value}/: ${show(got)}`;
    }
    case "type":
      return (Array.isArray(got) ? "array" : got === null ? "null" : typeof got) === e.value ? null : `${where} is ${show(got)}, expected a ${e.value}`;
    default:
      return `unknown op ${e.op}`;
  }
}

const b64 = (obj) => Buffer.from(JSON.stringify(obj)).toString("base64");

const HEX32 = /^[0-9a-f]{64}$/;

/**
 * A season's record, checked for whichever state it is in. Pure: the caller hands in what the
 * contract and the site answered.
 *
 *   open               get_season is null and the site has no results file (404)
 *   closed             get_season is still null and the site serves the frozen results (the
 *                      close has run; record_season hasn't landed yet)
 *   recorded           get_season holds a root, a digest and the top of the board; the site's
 *                      results file has that root, its sha256 is that digest, its first leaves
 *                      are that board in order, and each of them holds trophy:<id>:<rank>
 *
 * `input`: { id, endsAt?, now, season, results: { status, text }, balances?: string[] }.
 * Returns { state, problems }.
 */
export function seasonState(input) {
  const { id, season, results } = input;
  const problems = [];
  let file = null;
  if (results.status === 200) {
    try {
      file = JSON.parse(results.text);
    } catch {
      problems.push(`/api/seasons/${id}/results answered 200 with something that isn't JSON`);
    }
    if (file && (!HEX32.test(file.root ?? "") || !Array.isArray(file.leaves) || file.leaves.length === 0 || file.seasonId !== id)) problems.push(`/api/seasons/${id}/results has no root, no leaves or another season's id`);
  } else if (results.status !== 404) problems.push(`/api/seasons/${id}/results answered HTTP ${results.status}`);
  const ended = input.endsAt === undefined || input.now >= Date.parse(input.endsAt);
  if (file && !ended) problems.push(`the site serves final results for ${id} before its end (${input.endsAt})`);

  if (season === null) return { state: file ? "closed" : "open", problems };

  if (!ended) problems.push(`${id} is recorded on chain before its end (${input.endsAt})`);
  if (!HEX32.test(season.root ?? "")) problems.push("the recorded root isn't 32 bytes of hex");
  if (!HEX32.test(season.digest ?? "")) problems.push("the recorded digest isn't 32 bytes of hex");
  const top = Array.isArray(season.top10) ? season.top10 : [];
  if (top.length < 1 || top.length > 10) problems.push(`the recorded board holds ${top.length} accounts, expected 1 to 10`);
  if (!(Number(season.recorded_at_ms) > 0)) problems.push("the record has no time");
  if (!file) problems.push(`${id} is recorded on chain but /api/seasons/${id}/results answered HTTP ${results.status}`);
  else {
    if (file.root !== season.root) problems.push(`the results file's root ${file.root} isn't the recorded root ${season.root}`);
    const digest = createHash("sha256").update(results.text).digest("hex");
    if (digest !== season.digest) problems.push(`the results file's sha256 ${digest} isn't the recorded digest ${season.digest}`);
    const board = file.leaves.slice(0, top.length).map((l) => l.accountId);
    if (JSON.stringify(board) !== JSON.stringify(top)) problems.push(`the results file's top ${top.length} isn't the recorded board`);
  }
  const balances = input.balances ?? [];
  top.forEach((account, i) => {
    if (balances[i] !== "1") problems.push(`${account} holds ${balances[i] ?? "no"} trophy:${id}:${i + 1}, expected 1`);
  });
  return { state: "recorded", problems };
}

/**
 * Two figures worked out from /api/stats: seconds of verified play per verified run (all
 * modes together), and verified case-file runs summed over the cases.
 */
export function statsDerived(stats) {
  const runs = stats?.runs ?? {};
  const cases = Object.entries(runs.byMode ?? {}).filter(([mode]) => mode.startsWith("case-"));
  return {
    secondsPerVerifiedRun: runs.verified > 0 ? Math.round((runs.hoursVerified * 3600) / runs.verified) : null,
    caseVerified: cases.reduce((n, [, m]) => n + (m?.verified ?? 0), 0),
  };
}

/**
 * Who sent a set of transactions: the distinct senders, in the order first seen. Pure. For a
 * relayed call the sender is the account inside the delegate action, not the relayer.
 */
export function distinctSenders(senders) {
  const accounts = [...new Set(senders)];
  return { accounts, count: accounts.length, transactions: senders.length };
}

/**
 * What an account holds in the game contract, added up: its Bits, the items in its wallet and
 * the items it has listed (those sit in the contract's escrow). Pure: `player` is what
 * `get_player` answered and `account` what `market_account` did.
 */
export function holdingsOf(player, account) {
  const tokens = Array.isArray(player?.tokens) ? player.tokens : [];
  const amount = (v) => (Number.isFinite(Number(v)) ? Number(v) : 0);
  const bits = tokens.filter(([id]) => id === "item:bits").reduce((sum, [, v]) => sum + amount(v), 0);
  const items = tokens.filter(([id]) => typeof id === "string" && id.startsWith("item:") && id !== "item:bits").reduce((sum, [, v]) => sum + amount(v), 0);
  const listed = (Array.isArray(account?.open) ? account.open : []).reduce((sum, l) => sum + (l && typeof l === "object" ? amount(l.amount ?? 1) : 1), 0);
  return { bits, items, listed, total: bits + items + listed };
}

