/** Runs one check. Resolves to { ok: true } | { ok: false, why } | { skip: why }. */
async function runChainCheck(check, meta) {
  try {
    let value;
    const viewCall = async (method, args) => {
      const j = await rpc(meta.rpc, "query", { request_type: "call_function", finality: "final", account_id: check.contract ?? meta.contract, method_name: method, args_base64: b64(args) });
      if (!j.result?.result) throw new Error(`${method}: ${String(j.result?.error ?? j.error?.data ?? j.error?.message ?? JSON.stringify(j)).slice(0, 200)}`);
      return JSON.parse(Buffer.from(j.result.result).toString("utf8"));
    };
    if (check.kind === "season") {
      const season = await viewCall("get_season", { season_id: check.season });
      const res = await fetchJson(`${meta.site}/api/seasons/${check.season}/results`, { headers: { accept: "application/json" } });
      const results = { status: res.status, text: await res.text() };
      const balances = [];
      for (const [i, account] of (season?.top10 ?? []).entries()) balances.push(await viewCall("mt_balance_of", { account_id: account, token_id: `trophy:${check.season}:${i + 1}` }));
      const { state, problems } = seasonState({ id: check.season, endsAt: check.endsAt, now: Date.now(), season, results, balances });
      return problems.length ? { ok: false, why: `${problems.join("; ")}${check.whenFails ? `. ${check.whenFails}` : ""}` } : { ok: true, note: `${check.season} is ${SEASON_STATE_NOTE[state]}` };
    }
    if (check.kind === "holdings") {
      value = holdingsOf(await viewCall("get_player", { account_id: check.account }), await viewCall("market_account", { account_id: check.account }));
    } else if (check.kind === "senders") {
      // The senders of other checks' transactions, looked up again and counted.
      const senders = [];
      for (const id of check.of) {
        const tx = meta.checks[id];
        const j = await rpc(meta.archivalRpc, "tx", { tx_hash: tx.hash, sender_account_id: tx.sender, wait_until: "FINAL" });
        if (!j.result) return { ok: false, why: `tx ${tx.hash}: ${j.error?.data ?? j.error?.message ?? "no result"}` };
        const delegate = j.result.transaction.actions.find((a) => a.Delegate)?.Delegate.delegate_action;
        senders.push(delegate?.sender_id ?? j.result.transaction.signer_id);
      }
      value = distinctSenders(senders);
    } else if (check.kind === "view") {
      const j = await rpc(meta.rpc, "query", { request_type: "call_function", finality: "final", account_id: check.contract ?? meta.contract, method_name: check.method, args_base64: b64(check.args ?? {}) });
      const failure = j.result?.error ?? j.error?.data ?? j.error?.message;
      if (check.absent) {
        // The claim is that the deployed contract has no such method.
        if (j.result?.result) return { ok: false, why: `${check.method} now answers on ${check.contract ?? meta.contract}. ${check.whenFails ?? "The claim is out of date."}` };
        return /MethodNotFound/.test(String(failure)) ? { ok: true } : { ok: false, why: `${check.method}: expected MethodNotFound, got ${String(failure).slice(0, 200)}` };
      }
      if (!j.result?.result) return { ok: false, why: `${check.method}: ${String(failure ?? JSON.stringify(j)).slice(0, 200)}` };
      value = JSON.parse(Buffer.from(j.result.result).toString("utf8"));
    } else if (check.kind === "account") {
      const j = await rpc(meta.rpc, "query", { request_type: "view_account", finality: "final", account_id: check.account });
      const missing = j.error?.cause?.name === "UNKNOWN_ACCOUNT";
      if (!j.result && !missing) return { ok: false, why: `view_account: ${j.error?.data ?? JSON.stringify(j).slice(0, 200)}` };
      value = { exists: !missing, ...(j.result ?? {}) };
      if (check.keys && !missing) {
        // Also the account's access keys: every public key, and those with full access.
        const k = await rpc(meta.rpc, "query", { request_type: "view_access_key_list", finality: "final", account_id: check.account });
        if (!k.result?.keys) return { ok: false, why: `view_access_key_list: ${k.error?.data ?? JSON.stringify(k).slice(0, 200)}` };
        value.keys = k.result.keys.map((key) => key.public_key);
        value.fullAccessKeys = k.result.keys.filter((key) => key.access_key?.permission === "FullAccess").map((key) => key.public_key);
      }
    } else if (check.kind === "tx") {
      const j = await rpc(meta.archivalRpc, "tx", { tx_hash: check.hash, sender_account_id: check.sender, wait_until: "FINAL" });
      if (!j.result) return { ok: false, why: `tx ${check.hash}: ${j.error?.data ?? j.error?.message ?? "no result"}` };
      const actions = j.result.transaction.actions.flatMap((a) => (a.Delegate ? a.Delegate.delegate_action.actions : [a]));
      const delegate = j.result.transaction.actions.find((a) => a.Delegate)?.Delegate.delegate_action;
      value = {
        signer: j.result.transaction.signer_id,
        receiver: delegate?.receiver_id ?? j.result.transaction.receiver_id,
        sender: delegate?.sender_id ?? j.result.transaction.signer_id,
        relayed: !!delegate,
        actions: actions.map((a) => (typeof a === "string" ? a : a.FunctionCall ? a.FunctionCall.method_name : Object.keys(a)[0])),
        deposits: actions.map((a) => a.FunctionCall?.deposit).filter((d) => d !== undefined),
        succeeded: j.result.status?.SuccessValue !== undefined && j.result.receipts_outcome.every((o) => !o.outcome.status?.Failure),
        logs: j.result.receipts_outcome.flatMap((o) => o.outcome.logs),
      };
    } else if (check.kind === "http") {
      // A check with a `body` POSTs it as JSON (the Gas tank's dry quote); every other http check is a GET.
      const init = check.body
        ? { method: "POST", headers: { accept: "application/json", "content-type": "application/json" }, body: JSON.stringify(check.body) }
        : { headers: { accept: check.text ? "text/html" : "application/json" } };
      const res = await fetchJson(check.url, init);
      if (res.status !== (check.status ?? 200)) return { ok: false, why: `${check.url} answered HTTP ${res.status}` };
      value = check.text ? { text: await res.text() } : await res.json();
      if (check.derive === "stats") value = { ...value, derived: statsDerived(value) };
    } else if (check.kind === "git") {
      // Local, no network. Three questions a check can ask of this clone's history:
      //   order:   are these commits each an ancestor of the next (so they were made in this order)?
      //   ref:     does this branch exist here, and does it contain these commits?
      //   history: the date of the first commit, and how many commits carry an AI trailer.
      const git = (...args) => run("git", args, ROOT, 30_000);
      const has = (rev) => git("cat-file", "-e", `${rev}^{commit}`).status === 0;
      if (git("rev-parse", "--is-inside-work-tree").status !== 0) return { skip: "this isn't a git checkout, so commit history can't be read" };
      if (git("rev-parse", "--is-shallow-repository").stdout.trim() === "true") return { skip: "this is a shallow clone, so commit history can't be read (git fetch --unshallow)" };
      value = {};
      if (check.order) {
        const missing = check.order.filter((c) => !has(c));
        if (missing.length) return { skip: `commits ${missing.map((c) => c.slice(0, 7)).join(", ")} aren't in this clone` };
        value.inOrder = check.order.every((c, i) => i === 0 || git("merge-base", "--is-ancestor", check.order[i - 1], c).status === 0);
        value.dates = check.order.map((c) => git("show", "-s", "--format=%ad", "--date=format-local:%Y-%m-%d %H:%M", c).stdout.trim());
        value.added = check.order.map((c) => git("show", "--diff-filter=A", "--name-only", "--format=", c).stdout.split("\n").filter(Boolean));
      }
      if (check.ref) {
        const ref = [check.ref, `origin/${check.ref}`].find(has);
        if (!ref) return { skip: `the branch ${check.ref} isn't in this clone (git fetch origin ${check.ref}:${check.ref}), so its commits can't be checked here` };
        value.ref = ref;
        value.missing = (check.commits ?? []).filter((c) => !has(c) || git("merge-base", "--is-ancestor", c, ref).status !== 0);
        value.files = (check.files ?? []).filter((f) => git("cat-file", "-e", `${ref}:${f}`).status === 0);
        value.merged = git("merge-base", "--is-ancestor", ref, "HEAD").status === 0;
      }
      if (check.history) {
        value.firstCommit = git("log", "--max-parents=0", "--format=%ad", "--date=short", "HEAD").stdout.trim().split("\n").sort()[0];
        // An AI trailer is a real git trailer (Co-authored-by, matched case-insensitively by git) or a
        // "Generated with Claude" line. Words in a commit's body, such as "generated with ElevenLabs", are not one.
        const coAuthored = git("log", "--format=%h%x09%(trailers:key=co-authored-by,valueonly,separator=%x2C)", "HEAD").stdout.split("\n").filter((l) => /\t\S/.test(l)).map((l) => l.split("\t")[0]);
        const generated = git("log", "-i", "-E", "--grep=generated with \\[?claude", "--grep=noreply@anthropic\\.com", "--format=%h", "HEAD").stdout.split("\n").filter(Boolean);
        value.aiTrailers = [...new Set([...coAuthored, ...generated])];
      }
    } else if (check.kind === "command") {
      const res = run(check.command[0], check.command.slice(1), ROOT, check.timeoutMs ?? 180_000);
      const text = `${res.stdout ?? ""}${res.stderr ?? ""}`;
      if (/fetch failed|ENOTFOUND|ECONNREFUSED|EAI_AGAIN|ETIMEDOUT/.test(text)) return { skip: `${check.command.join(" ")} couldn't reach the network` };
      value = { exit: res.status, lines: text.split("\n") };
      if (check.json) {
        try {
          value.json = JSON.parse(res.stdout);
        } catch {
          return { ok: false, why: `${check.command.join(" ")} didn't print JSON (exit ${res.status})` };
        }
        if (check.skipUnless && !pick(value, check.skipUnless)) {
          const notes = (value.json.notes ?? []).join("; ");
          return { skip: `${check.command.join(" ")} couldn't read all of its source: ${notes || "no data"}`, rateLimited: /rate.?limit|429|too many/i.test(notes) };
        }
      }
    } else return { ok: false, why: `unknown check kind ${check.kind}` };
    const problems = (check.expect ?? []).map((e) => expectProblem(value, resolveExpect(e))).filter(Boolean);
    return problems.length ? { ok: false, why: `${problems.join("; ")}${check.whenFails ? `. ${check.whenFails}` : ""}` } : { ok: true };
  } catch (e) {
    if (e instanceof Offline) return { skip: e.message, rateLimited: e.rateLimited };
    if (isTimeout(e)) return { skip: `a request timed out (${e.message})` };
    return { ok: false, why: e.message };
  }
}

